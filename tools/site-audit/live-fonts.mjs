import { chromium } from 'playwright';
const b = await chromium.launch({ args: ['--host-resolver-rules=MAP sunrooof.com 23.227.38.32'] });
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const f = [];
p.on('response', r => { if (/font|woff|ttf|otf/i.test(r.url() + (r.headers()['content-type'] || ''))) f.push(r.url()); });
await p.goto('https://sunrooof.com/', { waitUntil: 'networkidle', timeout: 90000 }).catch(() => {});
const faces = await p.evaluate(() => [...document.fonts].map(x => x.family + ' ' + x.weight + ' ' + x.status));
console.log(f.join('\n')); console.log(faces.join('\n'));
const css = await p.evaluate(() => [...document.styleSheets].flatMap(s => { try { return [...s.cssRules].filter(r => r.type === 5).map(r => r.cssText.slice(0, 300)); } catch { return []; } }));
console.log(css.join('\n'));
await b.close();
